let LANG = "pl";
function t(key) {
  return (I18N[LANG] && I18N[LANG][key]) || (I18N.pl && I18N.pl[key]) || key;
}
function detectLang() {
  try {
    const saved = localStorage.getItem("tlk-lang");
    if (saved === "en" || saved === "pl") return saved;
  } catch (e) {}
  const nav = (navigator.language || "pl").toLowerCase();
  return nav.startsWith("en") ? "en" : "pl";
}
function applyI18n() {
  document.documentElement.lang = LANG;
  document.title = LANG === "en" ? "TAURON Women's League 2026/27" : "TAURON Liga Kobiet 2026/27";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key && I18N[LANG][key]) el.textContent = I18N[LANG][key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key && I18N[LANG][key]) el.setAttribute("placeholder", I18N[LANG][key]);
  });
  document.querySelectorAll(".lang button").forEach((b) => {
    b.classList.toggle("active", b.dataset.lang === LANG);
  });
  const upd = document.getElementById("updated");
  if (upd) upd.textContent = t("updated");
}
function setLang(next) {
  LANG = next === "en" ? "en" : "pl";
  try { localStorage.setItem("tlk-lang", LANG); } catch (e) {}
  applyI18n();
  if (typeof refresh === "function" && SEASON && MATCHES) refresh();
}
